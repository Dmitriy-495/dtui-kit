// Package digits рисует цифры и часы трёхстрочными семисегментными
// глифами (классический вид цифровых часов) — для часов, количества,
// цены и других чисел, которые должны выглядеть как «табло».
//
// Зачем своё (правило 2 из PHILOSOPHY.md): готового компактного
// семисегментного шрифта нет. Проверено: segmock/7segment.flf — 16 строк
// высотой; ANSI Shadow — блоки, не сегменты, лицензия неясна; встроенные
// в go-figure digital и lcd — «цифры в коробочках» и нечитаемые сегменты;
// шрифты PhMajerus требуют символов Unicode 16. Свой набор — это одна
// таблица ASCII-символов: фиксированная ширина, без внешних файлов и без
// риска log.Fatal из сторонней библиотеки.
//
// Пакет возвращает обычную строку без цвета: цвет, жирность и рамку
// задаёт вызывающий через lipgloss. Таймеров здесь нет: мигание
// двоеточия вычисляется из переданного времени, а тики (раз в 500 мс)
// даёт приложение.
package digits

import (
	"strings"
	"time"
)

// Height — высота любого текста в строках.
const Height = 3

// DigitWidth — ширина одной цифры в колонках. Все цифры одинаковой
// ширины, поэтому число не «дёргается» при смене значений.
const DigitWidth = 5

// glyph — три строки одной ширины.
type glyph [Height]string

// glyphs — единственная таблица внешнего вида. Хочешь другой стиль —
// правь только её (ширина строк внутри одного глифа должна совпадать).
//
// Сегменты: верх — «_» в строке 0, середина — «_» в строке 1,
// низ — «_» в строке 2, вертикали — «|».
var glyphs = map[rune]glyph{
	'0': {" ___ ", "|   |", "|___|"},
	'1': {"     ", "    |", "    |"},
	'2': {" ___ ", " ___|", "|___ "},
	'3': {" ___ ", " ___|", " ___|"},
	'4': {"     ", "|___|", "    |"},
	'5': {" ___ ", "|___ ", " ___|"},
	'6': {" ___ ", "|___ ", "|___|"},
	'7': {" ___ ", "    |", "    |"},
	'8': {" ___ ", "|___|", "|___|"},
	'9': {" ___ ", "|___|", " ___|"},
	'-': {"     ", " ___ ", "     "},
	':': {" ", ".", "."},
	'.': {" ", " ", "."},
	',': {" ", " ", ","},
	// Пробел — пустая колонка (ширина как у ':'), поэтому выключенное
	// двоеточие не меняет ширину часов.
	' ': {" ", " ", " "},
}

// lookup возвращает глиф символа; неизвестный символ рисуется как пробел.
func lookup(r rune) glyph {
	if g, ok := glyphs[r]; ok {
		return g
	}
	return glyphs[' ']
}

// Render рисует text (цифры и символы - : . , пробел) в Height строк,
// между символами одна пустая колонка. Неизвестные символы заменяются
// пробелом, паники нет. Возвращает многострочную строку без
// завершающего "\n".
func Render(text string) string {
	var rows [Height]strings.Builder
	first := true
	for _, r := range text {
		g := lookup(r)
		for i := range rows {
			if !first {
				rows[i].WriteByte(' ')
			}
			rows[i].WriteString(g[i])
		}
		first = false
	}
	out := make([]string, Height)
	for i := range rows {
		out[i] = rows[i].String()
	}
	return strings.Join(out, "\n")
}

// Width возвращает ширину Render(text) в колонках — чтобы раскладка
// могла заранее выделить место.
func Width(text string) int {
	w, first := 0, true
	for _, r := range text {
		if !first {
			w++
		}
		w += len(lookup(r)[0])
		first = false
	}
	return w
}

// ColonOn сообщает, виден ли разделитель в момент t: мигание раз в
// секунду — первые полсекунды виден, вторые полсекунды погашен.
// Чтобы мигание было ровным, приложение должно получать тик не реже
// раза в 500 мс.
func ColonOn(t time.Time) bool {
	return t.Nanosecond() < int(time.Second/2)
}

// Clock рисует время t как «ЧЧ:ММ» (24 часа) с мигающим разделителем.
// Ширина результата одна и та же в обоих состояниях и для любого
// времени.
func Clock(t time.Time) string {
	text := t.Format("15:04")
	if !ColonOn(t) {
		text = strings.Replace(text, ":", " ", 1)
	}
	return Render(text)
}
